#!/usr/bin/env bash
#
# mayhem/build.sh — build firo's libspark/secp256k1 fuzz harnesses and the libspark unit-test suite.
#
# Firo's own build is CMake + `depends` (bls-dash, tor, libevent, zmq, ...), none of which the libspark
# code needs. The harnesses only need the privacy-crypto sources, so they are compiled directly from the
# same source lists upstream's src/fuzz/Makefile uses, with the compile definitions CMake would inject.
# The one exception is spark_spend_parser (upstream's src/test/fuzz/spark_spend_parser.cpp): it calls
# spark::ParseSparkSpend in spark/state.cpp, which links the node's validation layer, so that target also
# gets the node sources, compiled below from the lists in src/CMakeLists.txt, and the dependencies baked in
# /opt/firo-deps by the Dockerfile (bls-dash, relic, tor, immer; libdb, libevent come from apt).
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

SRC="${SRC:-/mayhem}"
cd "$SRC"

FUZZ_DIR="$SRC/mayhem/build-fuzz"
TEST_DIR="$SRC/mayhem/build-test"
rm -rf "$FUZZ_DIR" "$TEST_DIR"

LIBS="-lgmp -lcrypto -lboost_thread -lboost_filesystem -lboost_program_options -lboost_chrono -lboost_system -lpthread"

