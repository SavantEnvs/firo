DEFS="-DHAVE_CONFIG_H=1 -DHAVE_ENDIAN_H=1 -DHAVE_BYTESWAP_H=1 -DHAVE_DECL_STRNLEN=1 -DHAVE_MAYBE_UNUSED=1 -DHAVE_DECL_DAEMON=0 -DENABLE_ZMQ=0"
for f in le16toh le32toh le64toh htole16 htole32 htole64 be16toh be32toh be64toh htobe16 htobe32 htobe64 \
         bswap_16 bswap_32 bswap_64 __builtin_clz __builtin_clzl __builtin_clzll; do
  DEFS="$DEFS -DHAVE_DECL_$(echo "$f" | tr a-z A-Z)=1"
