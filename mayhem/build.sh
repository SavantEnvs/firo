# compile_node <build-dir> <flags...>: <build-dir>/libfironode.a. Warnings are off: they are upstream's.
compile_node() {
  local d="$1"; shift
  local flags="$* -w"
  local inc="-I$d -I$d/x -I$SRC/src -I$SRC/src/secp256k1 -I$SRC/src/secp256k1/include -I$SRC/src/secp256k1/src $NODE_INC"
  local ldbdefs="-DLEVELDB_PLATFORM_POSIX -DLEVELDB_IS_BIG_ENDIAN=0 -DHAVE_CRC32C=0 -DHAVE_SNAPPY=0 -DHAVE_ZSTD=0 -DHAVE_FDATASYNC=1 -DHAVE_FULLFSYNC=0 -DHAVE_O_CLOEXEC=1"
  mkdir -p "$d/nodeobj"
  {
    printf 'cpp %s\n' $NODE_CPP $NODE_EXTRA_CPP
    printf 'c %s\n' $NODE_EXTRA_C
    printf 'ldb %s\n' $LEVELDB_SOURCES
  } | xargs -P "$MAYHEM_JOBS" -L1 sh -c '
    kind="$0"; f="$1"; o="'"$d"'/nodeobj/$(echo "$f" | tr / _).o"
    case "$kind" in
      cpp) '"$CXX"' -std=c++20 '"$flags $DEFS $inc"' -c "'"$SRC"'/src/$f.cpp" -o "$o" ;;
      c)   '"$CC"' -std=gnu11 '"$flags $DEFS $inc"' -c "'"$SRC"'/src/$f.c" -o "$o" ;;
      ldb) '"$CXX"' -std=c++17 '"$flags $DEFS $ldbdefs $inc"' -c "'"$SRC"'/src/leveldb/$f.cc" -o "$o" ;;
    esac'
  rm -f "$d/libfironode.a"
  ar rcs "$d/libfironode.a" "$d"/nodeobj/*.o
}
