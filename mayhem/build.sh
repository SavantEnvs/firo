FUZZ_INC="-I$FUZZ_DIR -I$FUZZ_DIR/x -I$SRC/src -I$SRC/src/secp256k1 -I$SRC/src/secp256k1/include -I$SRC/src/secp256k1/src -I$SRC/mayhem/harnesses"
