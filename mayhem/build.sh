-DENABLE_MODULE_ECDH=1 -DHAVE___INT128=1 -DUSE_FIELD_5X52=1 -DUSE_SCALAR_4X64=1 -DHAVE_BUILTIN_EXPECT=1 -DSECP256K1_BUILD=1"

# compile_all <build-dir> <flags...>: compile LIB_SOURCES + secp256k1.c into <build-dir>/libfiro.a
compile_all() {
  local d="$1"; shift
  local flags="$*"
  local inc="-I$d -I$d/x -I$SRC/src -I$SRC/src/secp256k1 -I$SRC/src/secp256k1/include -I$SRC/src/secp256k1/src"
  mkdir -p "$d/obj"
  printf '%s\n' $LIB_SOURCES | xargs -P "$MAYHEM_JOBS" -I{} sh -c \
    "$CXX -std=c++20 $flags $DEFS $inc -c $SRC/src/{}.cpp -o $d/obj/\$(echo {} | tr / _).o"
  $CC -std=gnu11 $flags $DEFS $inc -c "$SRC/src/secp256k1/src/secp256k1.c" -o "$d/obj/secp256k1.o"
  rm -f "$d/libfiro.a"
  ar rcs "$d/libfiro.a" "$d"/obj/*.o
}

